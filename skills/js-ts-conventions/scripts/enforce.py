#!/usr/bin/env python3
"""
Enforce the js-ts-conventions catalog in a repo.

Default mode renders the generated files (SHA-protected: a generated file you
edited is never overwritten without --force) and prints the one-line wiring
edit each lint config still needs:

    .js-ts-conventions/plugin.mjs, eslint.mjs, oxlint*.json, README.md, manifest.json
    .js-ts-conventions/overrides.json        (created once, then yours)
    .claude/rules/js-ts-conventions.md       (--agents claude)
    .cursor/rules/js-ts-conventions.mdc      (--agents cursor)

--ratchet freezes today's violations (after wiring) so convention rules can run as
errors for new code: ESLint >= 9.24 uses native bulk suppressions, oxlint gets
per-file exemptions in .js-ts-conventions/legacy.json.

--check verifies wiring, repo-config conflicts and edited generated files.
Exits 1 when something needs attention.

Usage:
    python3 scripts/enforce.py [--root .] [--agents claude,cursor] [--force] [--dry-run]
    python3 scripts/enforce.py --ratchet [--root .]
    python3 scripts/enforce.py --check [--root .]
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from analyze_repo import alias_scopes, analyze  # noqa: E402
from audit import config_conflicts, eslint_effective_rules  # noqa: E402
from lint_engine import eslint_supports_suppressions, oxlint_config, parse_oxlint  # noqa: E402
from utils import (  # noqa: E402
    MANIFEST_NAME, OVERRIDES_NAME, PLUGIN_NAMESPACE, PLUGIN_TEMPLATE, SKILL_DIR, SKILL_VERSION,
    STATE_DIR, applicable_preferences, convention_rules, load_catalog, load_overrides, now_iso,
    read_json, rel, severity_for, sha256_file, sha256_text, source_files, write_json,
)

TEMPLATES = SKILL_DIR / "templates"
LEGACY_NAME = "legacy.json"
AGENT_TARGETS = {
    "claude": (".claude/rules/js-ts-conventions.md", "claude-rule.md.tmpl"),
    "cursor": (".cursor/rules/js-ts-conventions.mdc", "cursor-rule.mdc.tmpl"),
}
OVERRIDES_TEMPLATE = {
    "_help": "See .js-ts-conventions/README.md. Globs are repo-root-relative.",
    "disabled": {},
    "severity": {},
    "exempt": {},
    "options": {},
    "scope": {},
}


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------

def template(name: str, **values: str) -> str:
    text = (TEMPLATES / name).read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace(f"__{key}__", value)
    return text


def enforcement_tag(pref: dict) -> str:
    enforce = pref.get("enforce", {})
    if enforce.get("eslint") or enforce.get("oxlint"):
        return "lint"
    return "tsconfig" if enforce.get("tsconfig") else "review"


def render_rules_body(catalog: dict, overrides: dict, snapshot: dict) -> str:
    prefs = [p for p in applicable_preferences(catalog, overrides, snapshot)
             if severity_for(p, catalog, overrides) != "off"]
    lines = [
        "# JS/TS conventions",
        "",
        f"Generated by the js-ts-conventions skill (catalog v{catalog['catalog_version']}). "
        "Rules tagged **lint** fail the linter; **tsconfig** rules fail the compiler; **review** rules "
        "are yours to follow. Do not edit this file: change `.js-ts-conventions/overrides.json`, then re-run enforce.",
        "",
    ]
    for level, heading in (("must", "Must"), ("should", "Should")):
        group = [p for p in prefs if p["level"] == level]
        if not group:
            continue
        lines += [f"## {heading}", ""]
        for pref in group:
            lang = {"strict-compiler": "json", "filename-case": "text"}.get(pref["id"], "ts")
            lines += [f"### {pref['title']} · {enforcement_tag(pref)}", "", pref["statement"], "",
                      f"Why: {pref['why']}", ""]
            if pref.get("notes"):
                lines += [pref["notes"], ""]
            exempt = overrides["exempt"].get(pref["id"])
            if exempt:
                lines += ["Exempt in this repo: " + ", ".join(f"`{g}`" for g in exempt) + ".", ""]
            lines += ["Avoid:", f"```{lang}", pref["bad"], "```", "Prefer:", f"```{lang}", pref["good"], "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def oxlint_target(unit: dict) -> str:
    slug = "" if unit["dir"] == "." else "." + unit["dir"].replace("/", "__")
    return f"{STATE_DIR}/oxlint{slug}.json"


def root_unit(snapshot: dict) -> dict:
    unit = {"dir": "."}
    unit["alias_scopes"] = alias_scopes(unit, snapshot["tsconfigs"])
    return unit


def generated_files(root: Path, snapshot: dict, catalog: dict, overrides: dict, agents: list[str]) -> dict[str, str]:
    version = {"VERSION": SKILL_VERSION, "CATALOG": str(catalog["catalog_version"])}
    files = {
        f"{STATE_DIR}/plugin.mjs": PLUGIN_TEMPLATE.read_text(encoding="utf-8"),
        f"{STATE_DIR}/README.md": template("state-readme.md.tmpl", **version),
    }
    legacy = read_json(root / STATE_DIR / LEGACY_NAME) or {}
    units = snapshot["lint_units"]
    for unit in [u for u in units if u["tool"] == "oxlint" and u.get("format") == "json"]:
        entries = convention_rules(catalog, overrides, "oxlint", snapshot, unit,
                              type_aware=bool(unit.get("type_aware_available")))
        config = oxlint_config(entries, catalog, "./plugin.mjs", anchored=False,
                               decorator_metadata=bool(unit.get("decorator_metadata")),
                               legacy=legacy.get(unit["dir"]))
        # oxlint rejects unknown keys, so the "generated, do not edit" note lives in README.md.
        files[oxlint_target(unit)] = json.dumps(config, indent=2) + "\n"
    if any(u["tool"] == "eslint" and u.get("format") == "flat" for u in units):
        entries = convention_rules(catalog, overrides, "eslint", snapshot, root_unit(snapshot), type_aware=True)
        files[f"{STATE_DIR}/eslint.mjs"] = template(
            "eslint.mjs.tmpl", **version,
            ENTRIES=json.dumps(entries, indent=2),
            IGNORES=json.dumps(catalog["ignores"]),
            DEFAULT_TS=json.dumps(catalog["file_sets"]["ts"]),
            DECORATOR_METADATA=json.dumps(bool(snapshot["decorator_metadata"])),
        )
    body = render_rules_body(catalog, overrides, snapshot)
    for agent in agents:
        target, tmpl = AGENT_TARGETS[agent]
        files[target] = template(tmpl, BODY=body.rstrip())
    return files


# ---------------------------------------------------------------------------
# SHA-protected writes
# ---------------------------------------------------------------------------

def write_generated(root: Path, files: dict[str, str], force: bool, dry_run: bool,
                    agents: list[str] | None = None) -> tuple[dict, list[str]]:
    manifest_path = root / STATE_DIR / MANIFEST_NAME
    manifest = read_json(manifest_path) or {}
    known: dict[str, str] = manifest.get("files", {})
    lines: list[str] = []
    new_known: dict[str, str] = {}
    for relpath, content in sorted(files.items()):
        path = root / relpath
        digest = sha256_text(content)
        current = sha256_file(path)
        if current == digest:
            new_known[relpath] = digest
            lines.append(f"  unchanged  {relpath}")
            continue
        edited = current is not None and (relpath not in known or current != known[relpath])
        if edited and not force:
            new_known[relpath] = known.get(relpath, "")
            lines.append(f"  SKIPPED    {relpath} (edited by hand or not ours; --force to overwrite)")
            continue
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        new_known[relpath] = digest
        lines.append(f"  {'created' if current is None else 'updated'}    {relpath}")
    for relpath, digest in known.items():
        if relpath in files:
            continue
        path = root / relpath
        if sha256_file(path) == digest:
            if not dry_run:
                path.unlink(missing_ok=True)
            lines.append(f"  removed    {relpath} (no longer generated)")
        elif path.exists():
            lines.append(f"  kept       {relpath} (no longer generated, but edited by hand)")
    overrides_path = root / STATE_DIR / OVERRIDES_NAME
    if not overrides_path.exists():
        if not dry_run:
            write_json(overrides_path, OVERRIDES_TEMPLATE)
        lines.append(f"  created    {STATE_DIR}/{OVERRIDES_NAME} (yours to edit)")
    manifest = {"skill_version": SKILL_VERSION, "generated_at": now_iso(),
                "agents": agents if agents is not None else manifest.get("agents", list(AGENT_TARGETS)),
                "files": new_known}
    if not dry_run:
        write_json(manifest_path, manifest)
    return manifest, lines


# ---------------------------------------------------------------------------
# Wiring instructions and checks
# ---------------------------------------------------------------------------

def relative_import(from_dir: str, target: str) -> str:
    path = os.path.relpath(target, from_dir if from_dir != "." else ".").replace(os.sep, "/")
    return path if path.startswith(("./", "../")) else "./" + path


def wiring_steps(snapshot: dict) -> list[str]:
    steps = []
    shared = set(snapshot["shared_config_packages"])
    for unit in snapshot["lint_units"]:
        if unit["tool"] == "oxlint":
            if unit.get("format") != "json":
                steps.append(f"`{unit['config']}`: JS/TS oxlint configs are not wired automatically; add the rules "
                             f"from `{oxlint_target(unit)}` by hand.")
            elif not unit.get("has_conventions_extends"):
                target = relative_import(unit["dir"], oxlint_target(unit))
                steps.append(f'`{unit["config"]}`: append "{target}" to `extends` (create the array if missing).')
        elif unit.get("format") == "legacy":
            steps.append(f"`{unit['config']}`: legacy config; migrate to flat config (`npx @eslint/migrate-config`), "
                         "then re-run enforce.")
        elif not unit.get("has_conventions_import"):
            target = relative_import(unit["dir"], f"{STATE_DIR}/eslint.mjs")
            unit_arg = "" if unit["dir"] == "." else f', {{ unit: "{unit["dir"]}" }}'
            via_shared = [i for i in unit.get("config_imports", []) if any(s.split("/")[-1] in i for s in shared)]
            hint = (f" It imports a shared preset ({', '.join(via_shared)}); wiring the preset instead covers every "
                    "package at once (call it without the `unit` option).") if via_shared else ""
            steps.append(f'`{unit["config"]}`: `import withConventions from "{target}";` and wrap the export: '
                         f"`export default withConventions([...]{unit_arg});`.{hint}")
    return steps


def unit_wired(root: Path, unit: dict, files: list[str], timeout: int) -> bool | None:
    if unit["tool"] == "oxlint":
        return bool(unit.get("has_conventions_extends"))
    effective = eslint_effective_rules(root, unit, files, timeout)
    if effective is None:
        return None
    return any(rule.startswith(PLUGIN_NAMESPACE + "/") for rule in effective["rules"])


def check(root: Path, snapshot: dict, catalog: dict, overrides: dict, timeout: int) -> int:
    files = source_files(root)
    problems = 0
    for unit in snapshot["lint_units"]:
        wired = unit_wired(root, unit, files, timeout)
        label = {True: "wired", False: "NOT wired", None: "unknown (could not run ESLint)"}[wired]
        print(f"{unit['tool']} `{unit['config']}`: {label}")
        problems += wired is False
    for conflict in config_conflicts(root, snapshot, catalog, overrides, files, timeout):
        if conflict["kind"] == "weaker":
            problems += 1
            print(f"conflict: {conflict['where']} sets `{conflict['rule']}` to `{conflict['repo']}` and wins "
                  f"(conventions: {conflict['conventions']}). Remove it, or record the exception in overrides.json.")
        elif conflict["kind"] == "shadowed":
            print(f"note: {conflict['where']} sets `{conflict['rule']}` to `{conflict['repo']}`, but the conventions "
                  f"override it ({conflict['conventions']}). Remove the setting to avoid confusion.")
    manifest = read_json(root / STATE_DIR / MANIFEST_NAME) or {}
    for relpath, digest in manifest.get("files", {}).items():
        if digest and sha256_file(root / relpath) not in (digest,):
            problems += 1
            print(f"edited: {relpath} differs from what enforce generated (re-run enforce, or --force).")
    print("OK" if not problems else f"{problems} problem(s).")
    return 1 if problems else 0


# ---------------------------------------------------------------------------
# Ratchet
# ---------------------------------------------------------------------------

def run(cmd: list[str], cwd: Path, timeout: int) -> tuple[int, str, str]:
    try:
        proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout,
                              env={**os.environ, "ESLINT_USE_FLAT_CONFIG": "true"})
    except (OSError, subprocess.SubprocessError) as exc:
        return 1, "", str(exc)
    return proc.returncode, proc.stdout, proc.stderr


def ratchet(root: Path, snapshot: dict, catalog: dict, overrides: dict, agents: list[str], timeout: int) -> int:
    files = source_files(root)
    legacy = read_json(root / STATE_DIR / LEGACY_NAME) or {}
    failures = 0
    for unit in snapshot["lint_units"]:
        unit_root = root / unit["dir"]
        if unit_wired(root, unit, files, timeout) is not True:
            print(f"skip `{unit['config']}`: not wired yet (run enforce and apply the wiring step first).")
            failures += 1
            continue
        if unit["tool"] == "oxlint":
            entries = convention_rules(catalog, overrides, "oxlint", snapshot, unit,
                                  type_aware=bool(unit.get("type_aware_available")))
            errors = {e["rule"] for e in entries if e["severity"] == "error"}
            legacy.pop(unit["dir"], None)
            write_json(root / STATE_DIR / LEGACY_NAME, legacy)
            write_generated(root, generated_files(root, snapshot, catalog, overrides, agents), False, False)
            cmd = [unit["binary"] or "oxlint", "-f", "json"]
            if unit.get("type_aware_available") and any(e["type_aware"] for e in entries):
                cmd.append("--type-aware")
            code, out, err = run([*cmd, "."], unit_root, timeout)
            payload = json.loads(out[out.find("{"):]) if "{" in out else None
            if payload is None:
                print(f"oxlint failed in `{unit['dir']}`: {(err or out)[:400]}")
                failures += 1
                continue
            frozen: dict[str, set[str]] = {}
            for violation in parse_oxlint(payload, unit_root, unit_root, errors):
                frozen.setdefault(violation["rule"], set()).add(violation["file"])
            legacy[unit["dir"]] = {rule: sorted(paths) for rule, paths in sorted(frozen.items())}
            write_json(root / STATE_DIR / LEGACY_NAME, legacy)
            write_generated(root, generated_files(root, snapshot, catalog, overrides, agents), False, False)
            count = sum(len(paths) for paths in frozen.values())
            print(f"oxlint `{unit['dir']}`: froze {count} file/rule pairs across {len(frozen)} rules in "
                  f"{STATE_DIR}/{LEGACY_NAME}. New files must comply.")
        elif unit.get("format") == "flat":
            if not eslint_supports_suppressions(unit.get("version")):
                print(f"eslint `{unit['dir']}` is {unit.get('version')}: bulk suppressions need >= 9.24. "
                      "Upgrade ESLint, or set convention rules to `warn` in overrides.json until fixed.")
                failures += 1
                continue
            entries = convention_rules(catalog, overrides, "eslint", snapshot, root_unit(snapshot), type_aware=True)
            cmd = [unit["binary"], ".", "-f", "json"]
            for rule in sorted({e["rule"] for e in entries if e["severity"] == "error"}):
                cmd += ["--suppress-rule", rule]
            code, out, err = run(cmd, unit_root, timeout)
            suppressions = read_json(unit_root / "eslint-suppressions.json") or {}
            count = sum(v.get("count", 0) for rules in suppressions.values() for v in rules.values()
                        if isinstance(v, dict))
            if code == 2:
                print(f"eslint failed in `{unit['dir']}`: {(err or out)[:400]}")
                failures += 1
                continue
            print(f"eslint `{unit['dir']}`: {count} violations suppressed in "
                  f"{rel(unit_root / 'eslint-suppressions.json', root)}. Commit it; after fixing code run "
                  "`eslint . --prune-suppressions`.")
    return 1 if failures else 0


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def pending_config_steps(root: Path) -> list[str]:
    audit = read_json(root / STATE_DIR / "audit.json") or {}
    return [f"`{gap['tsconfig']}`: enable " + ", ".join(f"`{m}`" for m in gap["missing"])
            for gap in audit.get("tsconfig_gaps", [])]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", default=".", help="Repository root (default: cwd)")
    parser.add_argument("--agents",
                        help="Agent rule files: claude, cursor (comma-separated) or none. "
                             "Default: the previous run's choice, else claude,cursor")
    parser.add_argument("--force", action="store_true", help="Overwrite generated files edited by hand")
    parser.add_argument("--dry-run", action="store_true", help="Show what would change; write nothing")
    parser.add_argument("--ratchet", action="store_true", help="Freeze existing violations (after wiring)")
    parser.add_argument("--check", action="store_true", help="Verify wiring and conflicts; exit 1 on problems")
    parser.add_argument("--timeout", type=int, default=600, help="Seconds per linter run")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    if args.agents is None:
        previous = (read_json(root / STATE_DIR / MANIFEST_NAME) or {}).get("agents")
        agents = previous if isinstance(previous, list) else list(AGENT_TARGETS)
    elif args.agents == "none":
        agents = []
    else:
        agents = [a.strip() for a in args.agents.split(",") if a.strip()]
    unknown = [a for a in agents if a not in AGENT_TARGETS]
    if unknown:
        parser.error(f"unknown --agents value(s): {', '.join(unknown)}")
    catalog = load_catalog()
    overrides = load_overrides(root)
    snapshot = analyze(root)

    if args.check:
        return check(root, snapshot, catalog, overrides, args.timeout)
    if args.ratchet:
        return ratchet(root, snapshot, catalog, overrides, agents, args.timeout)

    files = generated_files(root, snapshot, catalog, overrides, agents)
    _, lines = write_generated(root, files, args.force, args.dry_run, agents)
    print(("Dry run, nothing written:" if args.dry_run else "Generated files:"))
    print("\n".join(lines))
    steps = wiring_steps(snapshot)
    print("\nWiring (one edit per config):" if steps else "\nWiring: all lint configs already use the conventions config.")
    print("\n".join(f"  {i}. {step}" for i, step in enumerate(steps, 1)))
    config_steps = pending_config_steps(root)
    if config_steps:
        print("\nConfig steps from the last audit (see PLAN.md for impact):")
        print("\n".join(f"  - {step}" for step in config_steps))
    if not snapshot["lint_units"]:
        print("\nNo linter config found: add oxlint (`npm i -D oxlint`, then `.oxlintrc.json` with "
              f'`"extends": ["./{STATE_DIR}/oxlint.json"]`) and re-run enforce.')
    print("\nThen: enforce.py --ratchet to freeze existing violations, and enforce.py --check.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
